import assert from 'node:assert/strict';
import { build } from 'esbuild';
const result = await build({ entryPoints: ['src/lib/managerSetupModel.ts'], bundle: true, write: false, platform: 'node', format: 'esm' });
const { setupSteps, setupReady } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const keys = ['club','team','season','staff','roster','access','venues','matches','training','review'];
const full = {club_ready:true,team_ready:true,season_ready:true,staff:1,players:12,jerseys_missing:0,access:12,venues:2,matches:8,trainings:20,checks:{},updated_at:null};
assert.equal(setupReady(full), false, 'Data alone does not replace manual review');
assert.equal(setupSteps(full).every(s => s.state === 'review'), true);
const reviewed = {...full, checks:Object.fromEntries(keys.map(k => [k,'reviewed']))};
assert.equal(setupReady(reviewed), true);
assert.equal(setupReady({...reviewed,staff:0}), false, 'Removed staff invalidates completion');
assert.equal(setupReady({...reviewed,jerseys_missing:1}), false, 'Incomplete roster cannot be checked off');
assert.equal(setupReady({...reviewed,access:11}), false, 'All active players need access preparation');
assert.equal(setupReady({...reviewed,season_ready:false}), false, 'Archived/draft season cannot be ready');
const optional = {...reviewed,access:0,matches:0,trainings:0,checks:{...reviewed.checks,access:'unneeded',matches:'unneeded',training:'unneeded'}};
assert.equal(setupReady(optional), true);
assert.equal(setupReady({...reviewed,staff:0,checks:{...reviewed.checks,staff:'unneeded'}}), false, 'Mandatory steps cannot be skipped');
assert.equal(setupSteps({...full,players:0,access:0}).find(s=>s.key==='access').state,'missing');
assert.equal(setupSteps({...full,checks:{club:'reviewed'}}).filter(s=>s.state==='done').length,1, 'Progress belongs only to its snapshot');
console.log('PASS: ten steps, manual review, missing data, mandatory rules, optional steps and snapshot isolation');
