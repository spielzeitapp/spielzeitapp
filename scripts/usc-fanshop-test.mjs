import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const React = require('react');
const { create, act } = require('react-test-renderer');
const result = await build({ entryPoints: ['src/features/club/UscFanshop.tsx'], bundle: true, write: false, platform: 'node', format: 'cjs', external: ['react'], loader: { '.css': 'empty' } });
const mod = { exports: {} };
new Function('require', 'module', 'exports', result.outputFiles[0].text)(require, mod, mod.exports);
let tree;
act(() => { tree = create(React.createElement(mod.exports.UscFanshop, { onBack() {} })); });
const text = () => JSON.stringify(tree.toJSON());
const button = label => tree.root.findAllByType('button').find(node => node.children.filter(child => typeof child === 'string').join('') === label);
const click = node => { assert.ok(node); act(() => node.props.onClick()); };
click(button('Zubehör'));
assert.equal(tree.root.findAllByProps({ className: 'usc-shop-card' }).length, 1);
click(button('Alle'));
click(tree.root.findAllByProps({ className: 'usc-shop-card' })[0]);
assert.equal(button('Bitte Größe wählen').props.disabled, true);
click(button('140'));
const inputs = tree.root.findAllByType('input');
act(() => inputs[0].props.onChange({ target: { value: 'Johannes' } }));
act(() => inputs[1].props.onChange({ target: { value: '1a0' } }));
click(button('In den Warenkorb'));
click(button('In den Warenkorb'));
click(button('Warenkorb ansehen'));
assert.match(text(), /Johannes/);
assert.match(text(), /Nr. 10/);
assert.match(text(), /98,00/);
assert.equal(tree.root.findAllByProps({ className: 'usc-shop-cart-item' }).length, 1);
assert.equal(button('Bestellen bald möglich').props.disabled, true);
click(tree.root.findByProps({ 'aria-label': 'USC Hoodie: Menge verringern' }));
assert.match(text(), /49,00/);
click(tree.root.findByProps({ 'aria-label': 'USC Hoodie entfernen' }));
assert.match(text(), /Noch nichts im Warenkorb/);
assert.equal(button('Bestellen bald möglich'), undefined);
act(() => tree.unmount());
console.log('PASS USC Fanshop: category filter, size required, personalization, duplicate merging, totals, quantities, removal, empty state and disabled checkout.');
