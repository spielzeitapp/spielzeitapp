import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { createRequire } from 'node:module';
import fs from 'node:fs';
const require = createRequire(import.meta.url);
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const b = await build({ entryPoints: ['src/components/team/PlayerMatchContribution.tsx'], bundle: true, platform: 'node', format: 'cjs', packages: 'external', write: false, jsx: 'automatic' });
const m = { exports: {} };
new Function('require', 'module', 'exports', b.outputFiles[0].text)(require, m, m.exports);
const render = match => renderToStaticMarkup(React.createElement(m.exports.PlayerMatchContribution, { match }));
const base = { minutes: 75, minutesKnown: true, goals: 2, badgeKind: 'unknown', badgeLabel: '75 Min · berechnet' };
let html = render(base);
assert.match(html, /75 Min\./); assert.match(html, /2 Tore/); assert.match(html, /ÖFB-Aufstellung/);
html = render({ ...base, minutes: 0, minutesKnown: false, badgeLabel: 'ÖFB · Spielzeit offen' });
assert.match(html, /— Min\./); assert.doesNotMatch(html, /0 Min\./);
html = render({ ...base, minutes: 0, goals: 1, badgeKind: 'sub_in' });
assert.match(html, /0 Min\./); assert.match(html, /1 Tor</);
assert.match(render({ ...base, minutesKnown: undefined }), /75 Min\./);
const profile = fs.readFileSync('src/components/team/PlayerProfileModal.tsx', 'utf8');
assert.equal((profile.match(/<PlayerMatchContribution match=\{m\} \/>/g) || []).length, 2);
console.log('PASS: minutes beside goals for games and tournaments; calculated, unknown and confirmed zero stay distinct.');
